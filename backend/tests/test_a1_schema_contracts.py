"""Compare PostgreSQL-parsed CHECKs/defaults; Alembic autogenerate is not sufficient."""
import uuid

import pytest
import sqlalchemy as sa

from a1_postgresql import a1_postgres_url, a1_pg_engine, migrate, assert_owned_test_connection
from app.database import Base
from app.models import foundation, change_management, change_execution, notification, invitation, tenant_access_event


def _qualified(schema, name):
    return '"' + schema.replace('"', '""') + '"."' + name.replace('"', '""') + '"'


def _database_contract(connection, qualified_name):
    checks = dict(connection.execute(sa.text(
        "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint "
        "WHERE conrelid=to_regclass(:name) AND contype='c'"
    ), {"name": qualified_name}).all())
    defaults = dict(connection.execute(sa.text(
        "SELECT a.attname, pg_get_expr(d.adbin, d.adrelid) FROM pg_attribute a "
        "LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum "
        "WHERE a.attrelid=to_regclass(:name) AND a.attnum>0 AND NOT a.attisdropped"
    ), {"name": qualified_name}).all())
    return checks, defaults


def _contract_differences(connection, model):
    assert_owned_test_connection(connection)
    schema = connection.exec_driver_sql("SELECT current_schema()").scalar_one()
    actual_checks, actual_defaults = _database_contract(connection, _qualified(schema, model.name))
    # PostgreSQL parses the model expressions using the same column types. This
    # avoids guessing equivalence of IN/ANY, casts, whitespace, or parentheses.
    shadow = sa.Table(
        "a1_contract_" + uuid.uuid4().hex, sa.MetaData(),
        *(sa.Column(column.name, column.type, nullable=column.nullable,
                    server_default=sa.DefaultClause(column.server_default.arg) if column.server_default is not None else None)
          for column in model.columns),
        *(sa.CheckConstraint(str(check.sqltext), name=check.name)
          for check in model.constraints if isinstance(check, sa.CheckConstraint)),
        prefixes=["TEMPORARY"],
    )
    shadow.create(connection)
    try:
        expected_checks, expected_defaults = _database_contract(connection, _qualified("pg_temp", shadow.name))
    finally:
        shadow.drop(connection)
    # SERIAL defaults are generated by PostgreSQL for integer primary keys, not
    # explicit model server defaults. Every other column/default is compared.
    generated = {column.name for column in model.columns if column.primary_key
                 and isinstance(column.type, sa.Integer) and column.autoincrement in (True, "auto")
                 and column.server_default is None}
    actual_defaults = {key: value for key, value in actual_defaults.items() if key not in generated}
    expected_defaults = {key: value for key, value in expected_defaults.items() if key not in generated}
    differences = {}
    if actual_checks != expected_checks:
        differences["checks"] = (actual_checks, expected_checks)
    if actual_defaults != expected_defaults:
        differences["defaults"] = (actual_defaults, expected_defaults)
    return differences


def test_all_model_checks_and_server_defaults_match_postgresql(a1_pg_engine):
    with a1_pg_engine.begin() as connection:
        migrate(connection)
        assert len(Base.metadata.tables) == 20
        for table in Base.metadata.sorted_tables:
            assert not _contract_differences(connection, table), table.name


@pytest.mark.parametrize("replacement", [None, "membership_source IN ('legacy', 'invitation', 'bootstrap', 'unapproved')"])
def test_missing_or_changed_check_is_detected(a1_pg_engine, replacement):
    with a1_pg_engine.begin() as connection:
        migrate(connection)
        connection.exec_driver_sql("ALTER TABLE users DROP CONSTRAINT ck_users_membership_source")
        if replacement is not None:
            connection.exec_driver_sql("ALTER TABLE users ADD CONSTRAINT ck_users_membership_source CHECK (" + replacement + ")")
        assert "checks" in _contract_differences(connection, foundation.User.__table__)


@pytest.mark.parametrize("statement", [
    "ALTER TABLE users ALTER COLUMN membership_source DROP DEFAULT",
    "ALTER TABLE users ALTER COLUMN membership_source SET DEFAULT 'legacy'",
    "ALTER TABLE users ALTER COLUMN email SET DEFAULT 'unexpected@example.test'",
])
def test_missing_changed_or_unexpected_default_is_detected(a1_pg_engine, statement):
    with a1_pg_engine.begin() as connection:
        migrate(connection)
        connection.exec_driver_sql(statement)
        assert "defaults" in _contract_differences(connection, foundation.User.__table__)
